"""R24: how hard can the MuJoCo humanoid be pushed from the fighting stance? Writes data/push_limits.json.
  python tools/physics/push_limits.py [--out data/push_limits.json] [--workers 6]      (plain python, NOT -I: imports sim / kine_mjcf)
Stance = sim.make() default (scenes/hit_react.json card 0, the fighting stance), settled 0.3 s, then ONE impulse J (N s, a force J / 50 ms,
sim.Humanoid.hit) on a body, in one of 8 directions in the fighter's own frame (0 = forward +z, 90 = his left +x, 45-degree steps).
Outcome over the next 1.6 s: ABSORBS = no step taken and still up; STEPS = took a recovery step (sim.step_count > 0) and still up;
FALLS = sim.fallen() (pelvis < 0.55 m or head < 1.0 m). Impulses 5, 10 .. 60 N s, then a bisection to 1 N s on each boundary.
Per body and direction: absorb_max = the largest J absorbed in place, step_max = the largest J recovered with a step, fall_at = the
smallest J that falls (>= 61 = not within 60 N s). absorb_max < step_max < fall_at is the table's monotone order; a direction with no
stepped J has step_max == absorb_max and is listed in "no_step_band" (the stance goes from absorbing to falling inside 1 N s).
Bodies: chest = spine_03, stomach = spine_01, head, shoulder = upperarm_r."""
import argparse
import json
import os
import sys
from multiprocessing import Pool

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
BODIES = {"chest": "spine_03", "stomach": "spine_01", "head": "head", "shoulder": "upperarm_r"}
DIRS = list(range(0, 360, 45))
GRID = list(range(5, 61, 5))
SETTLE, WINDOW = 0.3, 1.6


def outcome(body, J, dir_deg):
    """0 absorbs, 1 steps, 2 falls: one sim run"""
    import sim
    h = sim.make()
    for _ in range(int(SETTLE / h.dt)):
        h.step()
    h.hit(body, float(J), float(dir_deg))
    for _ in range(int(WINDOW / h.dt)):
        h.step()
        if h.fallen():
            return 2
    return 1 if h.step_count > 0 else 0


def one(args):
    if os.name == "nt":
        import ctypes
        ctypes.windll.kernel32.SetPriorityClass(ctypes.windll.kernel32.GetCurrentProcess(), 0x4000)   # BELOW_NORMAL
    name, d = args
    body = BODIES[name]
    memo = {}

    def o(J):
        if J not in memo:
            memo[J] = outcome(body, J, d)
        return memo[J]
    first_step = fall = None
    prev = 0
    for J in GRID:
        v = o(J)
        if v >= 1 and first_step is None:
            first_step = J
        if v == 2:
            fall = J
            break
    # bisect the boundaries to 1 N s (the outcome is assumed monotone in J between grid points; the table is checked for it)
    if first_step is None:
        absorb_max = 60
    else:
        lo, hi = first_step - 5, first_step     # lo absorbs (or 0), hi does not
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if lo == 0 and mid == 0:
                break
            if o(mid) == 0:
                lo = mid
            else:
                hi = mid
        absorb_max = lo
    if fall is None:
        fall_at = 61
    else:
        lo, hi = fall - 5, fall                 # lo does not fall (or 0), hi falls
        lo = max(lo, 0)
        while hi - lo > 1:
            mid = (lo + hi) // 2
            if o(mid) == 2:
                hi = mid
            else:
                lo = mid
        fall_at = hi
    stepped = [J for J, v in memo.items() if v == 1 and J < fall_at]
    step_max = max(stepped) if stepped else absorb_max
    return name, d, {"absorb_max": absorb_max, "step_max": step_max, "fall_at": fall_at}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=os.path.join(HERE, "..", "..", "data", "push_limits.json"))
    ap.add_argument("--workers", type=int, default=6)
    ap.add_argument("--spot", nargs=3, metavar=("BODY", "J", "DIR"), help="one run: prints 0 absorbs / 1 steps / 2 falls (tests/r24_test.gd)")
    a = ap.parse_args()
    if a.spot:
        print(outcome(a.spot[0], float(a.spot[1]), float(a.spot[2])))
        return
    jobs = [(n, d) for n in BODIES for d in DIRS]
    with Pool(a.workers) as p:
        res = p.map(one, jobs, chunksize=1)
    tab = {n: {} for n in BODIES}
    for n, d, r in res:
        tab[n][str(d)] = r
    nostep = [f"{n}@{d}" for n in tab for d, r in tab[n].items() if r["step_max"] <= r["absorb_max"]]
    out = {"what": "largest impulse (N s) the MuJoCo humanoid absorbs in place / recovers with a step / falls at, from the fighting stance "
           "(scenes/hit_react.json), per struck body and push direction (deg, 0 = from behind pushing forward +z, 90 = toward his left +x). "
           "Generated by tools/physics/push_limits.py; do not edit.",
           "impulse_unit": "N s", "resolution": 1, "max_tested": 60, "fall_at_61_means": "no fall within 60 N s",
           "bodies": BODIES, "dirs": DIRS, "settle_s": SETTLE, "window_s": WINDOW, "no_step_band": nostep, "table": tab}
    with open(a.out, "w") as f:
        json.dump(out, f, indent=1)
    print("wrote", os.path.abspath(a.out), "no_step_band", len(nostep))


if __name__ == "__main__":
    main()
