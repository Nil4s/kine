"""Write docs/AGENT_MATH.md: the maths an agent that cannot see needs to work the poser (GATES V2). The joint table is
GENERATED from data/body_limits.json (limits and what + means), so it cannot drift from what the body does;
tests/py/measure_check.py regenerates it and fails if the file on disk differs.
  python tools/agent_math_doc.py [--check]"""
import json, os, sys

PROJ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(PROJ, "docs", "AGENT_MATH.md")

HEAD = """# The maths for an agent that cannot see the poser

GENERATED by tools/agent_math_doc.py from data/body_limits.json. Do not edit it by hand: run the tool.
How the numbers are made in full: MATH.md. How to drive the poser: README_AI.md (serve, MCP).

## Space and units
- Character space, **metres**: **+Y up, +Z forward (he faces +Z), +X = HIS LEFT**. The floor is y = 0.
- Angles are **degrees**. Times are **seconds**; a frame is t = frame / fps (the scene's fps unless you give one).
- The dummy (when it is on) stands `dist` m out in front of him (+Z), facing him.
- Every number `state` and `measure` return is rounded to 0.0001 m / 0.01 deg. Underneath it is exact and
  deterministic: the same t gives the same body in any process, whatever was asked before (tests/determinism_test.gd).

## A pose
Each joint has three angles, always in this order: **bend, side, twist**. They are rotations about the joint's own
three axes, fixed at rest: bend about its side axis, side about its front axis, twist along the bone. Plus the hips'
`offset` (m), which moves the whole body. Angles are clamped to the limits below. The answer to a `pose` request says
what each joint REACHED; a shortfall means a limit or a contact (the body never passes through itself or the bat).

## `state {t}`: where things are
- `joints`: name -> {bend, side, twist} (deg)
- `points`: 17 parts -> [x, y, z] (m): head, pelvis, spine_03 (the upper chest), upperarm_l/r (the shoulders),
  lowerarm_l/r (the elbows), hand_l/r (the wrists), thigh_l/r (the hips), calf_l/r (the knees), foot_l/r (the ankles),
  ball_l/r (the balls of the feet). A part's point is where its bone STARTS: its joint.
- `weapon`: kind, length (m), the hand holding it, knob and tip points (m)
- `plays`: "the cards as made" or "landed on the dummy" (the solid dummy stops the swing: what the window plays)

## `measure {t, what: [...]}`: numbers you would otherwise eyeball
Parts: any joint name, or `weapon_tip` / `weapon_knob`. Every answer carries its unit.
- `distance A B`: |A - B| (m)
- `angle A B C`: the angle at B between B->A and B->C (deg, 0..180). `angle upperarm_r lowerarm_r hand_r` is the
  elbow's opening: 180 = straight.
- `height A`: A's y (m above the floor)
- `speed A`: |A(t + h) - A(t - h)| / 2h with h = 1 / fps (m/s; a central difference, one-sided at the ends). A real
  bat or staff strike: 10 to 20 m/s at the tip. A walk's hips: 1 to 2 m/s.
- `clearance`: the closest the weapon comes to the dummy, surface to surface: the smallest
  |axis_w - axis_p| - r_w - r_p over every weapon capsule and dummy part (m; < 0 = in it, by that much), and the part.
- `com`: the centre of mass [x, y, z] (m): sum of m_i c_i / sum of m_i over 17 parts, c_i = the middle of the part's
  capsule, m_i = its share of the body (de Leva 1996): head 6.94, pelvis 11.17, spine_01 and spine_02 8.165 each,
  spine_03 15.96, upper arm 2.71, forearm 1.62, hand 0.61, thigh 14.16, shank 4.33, foot 1.37 (% each; 100 in all).
- `balance`: the com's floor point (x, z) to the edge of the support polygon (m; + inside, - past it), and the feet
  down. The polygon: the convex hull of each foot capsule's shadow where its underside is within 1 cm of the floor.
  At rest he stands 0.07 m inside. CHECK warns (BALANCE) past 3 cm for 0.1 s with both feet down.

## The joints: limits and what + means
| joint | bend | side | twist | what + means |
|---|---|---|---|---|
"""


def table(limits):
    rows = []
    for j, v in limits.items():
        if j.startswith("_") or not isinstance(v, dict) or "bend" not in v:
            continue
        say = v.get("say", {})
        means = "; ".join("%s: %s" % (k, say[k]) for k in ("bend", "side", "twist") if k in say) or "-"
        rows.append("| %s | %s..%s | %s..%s | %s..%s | %s |" % (j, v["bend"][0], v["bend"][1], v["side"][0], v["side"][1],
                                                               v["twist"][0], v["twist"][1], means.replace("|", "/")))
    return "\n".join(rows) + "\n"


def text():
    limits = json.load(open(os.path.join(PROJ, "data", "body_limits.json"), encoding="utf-8"))
    return HEAD + table(limits)


if __name__ == "__main__":
    t = text()
    if "--check" in sys.argv:
        same = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == t
        print("AGENT_MATH current" if same else "AGENT_MATH STALE: run python tools/agent_math_doc.py")
        sys.exit(0 if same else 1)
    open(OUT, "w", encoding="utf-8", newline="\n").write(t)
    print("wrote %s (%d joints)" % (OUT, t.count("\n| ") - 1))
